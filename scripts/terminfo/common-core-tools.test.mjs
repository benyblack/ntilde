import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, isAbsolute } from 'node:path';
import { execFileSync } from 'node:child_process';
import { commonCoreGit, assertCleanCommonCoreSource } from './common-core-tools.mjs';
test('Git dispatch is absolute and dirty/replaced source is refused before GUI work', (t) => {
    const directory = mkdtempSync(join(tmpdir(), 'common-core-source-test-'));
    t.after(() => rmSync(directory, { recursive: true, force: true }));
    const git = commonCoreGit();
    assert.ok(isAbsolute(git));
    const command = (...args) => execFileSync(git, args, { cwd: directory, stdio: ['ignore', 'pipe', 'pipe'] });
    command('init', '--quiet');
    command('config', 'user.name', 'Test');
    command('config', 'user.email', 'test@example.invalid');
    writeFileSync(join(directory, 'collector.mjs'), 'export const pin=1;\n');
    command('add', '.');
    command('commit', '-qm', 'fixture');
    const revision = assertCleanCommonCoreSource(directory);
    assert.match(revision, /^[a-f0-9]{40}$/);
    writeFileSync(join(directory, 'collector.mjs'), 'export const pin=2;\n');
    assert.throws(() => assertCleanCommonCoreSource(directory), /uncommitted/);
    command('add', '.');
    command('commit', '-qm', 'changed fixture');
    assert.throws(() => assertCleanCommonCoreSource(directory, revision), /revision changed/);
    writeFileSync(join(directory, 'untracked.mjs'), 'unsafe');
    assert.throws(() => assertCleanCommonCoreSource(directory), /uncommitted/);
});
